// Generates db/seed.sql (Cloudflare D1 / SQLite) from seed-data.ts. Run: npm run seed:generate
// Uses the same parser as the in-app import, so the tests cover the real seed.
import { createHash } from 'node:crypto';
import { buildImportPlan, parsePairingText, type ImportPlan } from '../../src/lib/pairingText.ts';
import { DEFAULT_RING } from '../../src/lib/rings.ts';
import { PAIRING_1, PAIRING_2 } from './seed-data.ts';

/** Deterministic UUID from a hint, so regenerating gives an identical seed.sql. */
export function stableId(hint: string): string {
  const h = createHash('sha256').update('oudeluck:' + hint).digest('hex');
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-4${h.slice(13, 16)}-a${h.slice(17, 20)}-${h.slice(20, 32)}`;
}

export const SEASON = { id: stableId('season:2026'), name: '2026 breeding', year: 2026 };
export const SEQUENCES = [
  { id: stableId('seq:2901'), start: 2901, end: 3000 },
  { id: stableId('seq:3901'), start: 3901, end: 4000 },
];

export function buildSeedPlan(): ImportPlan & { parseIssues: string[] } {
  const p1 = parsePairingText(PAIRING_1, 'box');
  const p2 = parsePairingText(PAIRING_2, 'block');
  const plan = buildImportPlan({
    sections: [
      { pairingNo: 1, pairs: p1.pairs },
      { pairingNo: 2, pairs: p2.pairs },
    ],
    ring: DEFAULT_RING,
    newId: stableId,
  });
  const parseIssues = [
    ...p1.issues.map((i) => `Pairing 1 line ${i.line}: ${i.message}`),
    ...p2.issues.map((i) => `Pairing 2 line ${i.line}: ${i.message}`),
  ];
  return { ...plan, parseIssues };
}

const q = (v: string | number | null): string =>
  v == null ? 'null' : typeof v === 'number' ? String(v) : `'${v.replace(/'/g, "''")}'`;

export function seedSql(): string {
  const plan = buildSeedPlan();
  const out: string[] = [];
  out.push('-- GENERATED by db/seed/generate-seed.ts — do not edit by hand.');
  out.push('-- Known data issues (imported as-is, not fixed):');
  for (const n of [...plan.parseIssues, ...plan.notes]) out.push(`--   ${n}`);
  out.push('-- Loaded automatically by the deploy workflow only when the database has no birds.');
  out.push(
    `insert into seasons (id, name, year, is_active) values (${q(SEASON.id)}, ${q(SEASON.name)}, ${SEASON.year}, 1);`,
  );
  for (const s of SEQUENCES) {
    out.push(
      `insert into ring_sequences (id, country, code, year, start_no, end_no, notes) values (${q(s.id)}, ${q(DEFAULT_RING.country)}, ${q(DEFAULT_RING.code)}, ${DEFAULT_RING.year}, ${s.start}, ${s.end}, 'Seeded guess — edit to match the rings actually issued');`,
    );
  }
  for (const b of plan.boxes) {
    out.push(`insert into boxes (id, name, section, sort_order) values (${q(b.id)}, ${q(b.name)}, ${q(b.section)}, ${b.sort_order});`);
  }
  // Parents first (no clutch), then youngsters after clutches exist.
  const birdRow = (b: ImportPlan['birds'][number]) =>
    `insert into birds (id, name, sex, ring_country, ring_number, ring_code, ring_year, sire_id, dam_id, clutch_id) values (${[
      b.id, b.name, b.sex, b.ring_country, b.ring_number, b.ring_code, b.ring_year, b.sire_id, b.dam_id, b.clutch_id,
    ].map(q).join(', ')});`;
  for (const b of plan.birds.filter((b) => !b.clutch_id)) out.push(birdRow(b));
  for (const p of plan.pairings) {
    out.push(
      `insert into pairings (id, season_id, pairing_no, box_id, block, cock_id, hen_id, sort_order) values (${[
        p.id, SEASON.id, p.pairing_no, p.box_id, p.block, p.cock_id, p.hen_id, p.sort_order,
      ].map(q).join(', ')});`,
    );
  }
  for (const c of plan.clutches) {
    out.push(`insert into clutches (id, pairing_id, round_no) values (${q(c.id)}, ${q(c.pairing_id)}, ${c.round_no});`);
  }
  for (const b of plan.birds.filter((b) => b.clutch_id)) out.push(birdRow(b));
  return out.join('\n') + '\n';
}

if (import.meta.url === `file://${process.argv[1]}`) {
  process.stdout.write(seedSql());
}
